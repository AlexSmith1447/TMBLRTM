import assert from "node:assert/strict";
import {tasteProfile,suggestedTags,eraAnchors,oldestEraTimestamp,scorePost,rankDiscovered} from "../src/discovery.js";
const liked={"1":{id:"1",blog:"scene-blog",tags:["emo","scene","music"],notes:220}};
const saved={"2":{id:"2",blog:"pixel-tunes",tags:["nintendocore","8bit"],notes:30}};
const profile=tasteProfile(liked,saved,["my-favorite-blog"]);
assert.ok(profile.weights.get("emo")>=5);
assert.ok(profile.weights.get("nintendocore")>=7);
assert.ok(profile.weights.get("scene")>=5);
assert.ok(profile.blogWeights.get("scene blog")>0);
const topics=suggestedTags(profile,0,4);
assert.ok(topics.includes("emo"));
assert.ok(topics.includes("nintendocore"));
assert.equal(topics.length,4);
assert.notDeepEqual(topics,suggestedTags(profile,1,4));
const anchors=eraAnchors("2012-12-31",[0,4,8,10]);
assert.equal(new Set(anchors).size,4);
assert.ok(anchors[0]>anchors[1]&&anchors[1]>anchors[2]);
assert.equal(new Date((anchors[0]-1)*1000).toISOString().slice(0,10),"2012-12-31");
assert.ok(anchors.every(x=>x>=oldestEraTimestamp("2012-12-31",12)));
const older={id:"old",blog:"old-blog",timestamp:1326000000,date:"2012-01-08",tags:["emo"],notes:40000,images:["https://x.example/old.jpg"],text:""};
const newer={id:"new",blog:"new-blog",timestamp:1356000000,date:"2012-12-20",tags:["emo"],notes:2,images:[],text:"a trivial recent post"};
const popular=rankDiscovered([newer,older,older],profile,{sort:"top",tag:"emo"});
assert.equal(popular.length,2,"deduplicate repeated timestamps across monthly samples");
assert.equal(popular[0].id,"old","older post with more notes should rank ahead of recent unpopular post");
const chronological=rankDiscovered([newer,older],profile,{sort:"recent",tag:"emo"});
assert.equal(chronological[0].id,"new");
const own={...older,id:"1",blog:"scene-blog"};
assert.ok(scorePost(own,profile,{sort:"top",tag:"emo"})<scorePost(older,profile,{sort:"top",tag:"emo"})+8,"liked post gets a novelty penalty");
const diverse=Array.from({length:12},(_,i)=>({id:"a"+i,blog:"popular",timestamp:1300000000-i,notes:1e6-i,tags:[],images:[]}))
 .concat(Array.from({length:4},(_,i)=>({id:"b"+i,blog:"other",timestamp:1290000000-i,notes:40000-i,tags:[],images:[]})));
const top=rankDiscovered(diverse,profile,{sort:"top"});
assert.ok(top.slice(0,7).filter(x=>x.blog==="other").length>=2,"avoid one blog taking over first page");
console.log("DISCOVERY_ALGORITHM_OK: tastes, era-window coverage, historical cutoff, ranking, deduplication and source diversity");
